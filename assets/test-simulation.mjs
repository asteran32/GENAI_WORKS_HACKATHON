import assert from 'node:assert/strict';
import { ambientTemperature, streetTemperature, coolingDrop, coolingPriority, scenarioTemperature } from './dist/simulation.js';
const base = {power:65,humidity:42,windKmh:12,temperature:33};
assert.equal(coolingDrop({...base,power:0}),0);
assert.equal(coolingDrop({...base,humidity:100}),0);
assert.equal(coolingDrop({...base,distanceMeters:100}),0);
assert.ok(coolingDrop({...base,power:90}) > coolingDrop(base));
assert.ok(coolingDrop({...base,humidity:75}) < coolingDrop(base));
assert.ok(coolingDrop({...base,distanceMeters:15}) < coolingDrop(base));
assert.equal(scenarioTemperature(33,[],true),33);
assert.equal(scenarioTemperature(33,[2,3],false),33);
assert.equal(scenarioTemperature(33,[2,3],true),30);
assert.ok(streetTemperature(15,1) < streetTemperature(15,0));
assert.ok(ambientTemperature(15,true) < ambientTemperature(15,false));
const need = {temperature:33,footfall:1800,minutesToShade:120};
assert.ok(coolingPriority(need) > coolingPriority({...need,minutesToShade:0}));
assert.ok(coolingPriority(need) > coolingPriority({...need,footfall:500}));
console.log('13 scenario-model assertions passed.');
assert.ok(coolingDrop({...base,windKmh:30})<coolingDrop(base));
assert.equal(coolingDrop({...base,distanceMeters:20+.24*base.power}),0);
assert.equal(coolingPriority({...need,minutesToShade:Infinity}),coolingPriority({...need,minutesToShade:120}));
assert.equal(coolingPriority({temperature:25,footfall:0,minutesToShade:0}),0);
assert.equal(coolingPriority({temperature:35,footfall:2400,minutesToShade:120}),100);
console.log('Wind, radius boundary and score-normalisation assertions passed.');
