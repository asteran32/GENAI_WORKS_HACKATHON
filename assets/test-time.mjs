import assert from 'node:assert/strict';
import { scenarioInstant, scenarioOffset, formatHour, formatScenarioDate, solarAt, naturalComparisonHour, validScenarioDate } from './dist/scenario-time.js';
assert.equal(scenarioOffset('2026-10-27'),11);
assert.equal(scenarioOffset('2026-07-15'),10);
assert.equal(scenarioInstant('2026-10-27',15).toISOString(),'2026-10-27T04:00:00.000Z');
assert.equal(scenarioInstant('2026-07-15',15).toISOString(),'2026-07-15T05:00:00.000Z');
assert.equal(formatHour(8),'08:00');
assert.equal(formatHour(17+55/60),'17:55');
assert.ok(formatScenarioDate('2026-10-27').includes('AEDT'));
assert.ok(formatScenarioDate('2026-07-15').includes('AEST'));
assert.equal(scenarioOffset('2026-04-05'),10);
assert.equal(scenarioOffset('2026-10-04'),11);
assert.equal(validScenarioDate('2026-02-30'),false);
assert.equal(validScenarioDate('2028-02-29'),true);
assert.equal(validScenarioDate(''),false);
assert.ok(solarAt(12,'2026-10-27').altitude>solarAt(12,'2026-07-15').altitude);
assert.ok(Math.abs(Math.hypot(...solarAt(15).direction)-1)<1e-12);
assert.equal(naturalComparisonHour(15),16);
assert.equal(naturalComparisonHour(17.5),18);
assert.equal(naturalComparisonHour(18),18);
console.log('18 Sydney date, daylight-saving, solar and time-boundary assertions passed.');
