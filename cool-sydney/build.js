'use strict';
const fs = require('node:fs');
const path = require('node:path');
function build() {
  const target = path.join(__dirname, 'public'); fs.mkdirSync(target, { recursive: true });
  for (const [source, name] of [['city.html','index.html'],['city.css','city.css'],['city-app.mjs','city-app.mjs'],['agent-panel.mjs','agent-panel.mjs'],['city-scene.mjs','city-scene.mjs'],['sun.mjs','sun.mjs'],['mist-model.mjs','mist-model.mjs'],['submission-deck.html','submission-deck.html']]) fs.copyFileSync(path.join(__dirname,'src',source),path.join(target,name));
  // A server process from an older revision can serve the updated HTML while
  // missing newly added asset routes. Keep the layout visible in that case.
  const html = fs.readFileSync(path.join(target,'index.html'),'utf8').replace('<link rel="stylesheet" href="/city.css">', () => `<style>${fs.readFileSync(path.join(target,'city.css'),'utf8')}</style>`);
  fs.writeFileSync(path.join(target,'index.html'), html);
  fs.cpSync(path.join(__dirname,'vendor'),path.join(target,'vendor'),{ recursive: true });
  return { path: path.join(target,'index.html'), mode: 'server-backed-real-gis' };
}
async function buildMonitor() {
  const {describeGraph}=require('./agent');
  const graph=await describeGraph();
  const renderer=fs.readFileSync(path.join(__dirname,'src/agent-graph.mjs'),'utf8').replace(/^export /gm,'');
  const entry=fs.readFileSync(path.join(__dirname,'src/agent-monitor-entry.mjs'),'utf8');
  // Existing 8766 servers already serve this single asset. No new module route
  // or graph endpoint is needed to display the compiled topology snapshot.
  fs.writeFileSync(path.join(__dirname,'src/agent-monitor.mjs'),
    `// Generated by buildMonitor(); edit agent-monitor-entry.mjs / agent-graph.mjs.\nconst initialGraph=${JSON.stringify(graph)};\n${renderer}\n${entry}`);
  return {graph_nodes:graph.nodes.length,graph_edges:graph.edges.length};
}
if (require.main === module) {console.log(build());buildMonitor().then(console.log).catch(error=>{console.error(error);process.exitCode=1;});}
module.exports = { build, buildMonitor };
